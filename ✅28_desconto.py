# Atividade 28 — Cálculo de desconto
#
# Crie uma função chamada calcular_desconto(valor, percentual).
#
# A função deverá retornar o valor do desconto.
#
# Dica:
# Calcule:
# valor * percentual / 100

def calcular_desconto(valor, percentual):
    return valor * percentual / 100


